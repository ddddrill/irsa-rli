"""Централизованный источник случайности для эффектов реализма.

Все стохастические эффекты (случайные фазы рассеивателей, анизотропия,
фазовый шум) берут числа из генераторов, порождаемых здесь, — это даёт
полную воспроизводимость при повторных запусках с одним seed.

Именованные под-генераторы (spawn_rng) гарантируют, что включение одного
эффекта не меняет случайную последовательность другого.
"""
import zlib

import numpy as np


def get_rng(seed: int) -> np.random.Generator:
    """Главный генератор случайных чисел проекта."""
    return np.random.default_rng(seed)


def spawn_rng(seed: int, name: str) -> np.random.Generator:
    """Детерминированный под-генератор для отдельного эффекта.

    Имя эффекта хешируется стабильной функцией (crc32), поэтому seed
    под-генератора не зависит от PYTHONHASHSEED и одинаков между запусками.

    Args:
        seed: базовый seed из конфигурации.
        name: имя эффекта ("complex_sigma", "anisotropy", ...).

    Returns:
        Независимый генератор np.random.Generator.
    """
    sub_seed = (zlib.crc32(name.encode("utf-8")) + int(seed)) % (2 ** 32)
    return np.random.default_rng(sub_seed)
